/**
 * Resolves current language with safe regional fallback for minor dialects.
 */
function resolveEffectiveLanguage(lang: string): string {
  if (!lang) return 'en';
  const l = lang.toLowerCase();
  if (['en', 'te', 'mr', 'hi', 'ta', 'kn', 'ml'].includes(l)) {
    return l;
  }
  // Dialect script mapping
  if (['tcy', 'kfa', 'bgy', 'bfq'].includes(l)) return 'kn';
  if (['kok'].includes(l)) return 'mr';
  return 'en';
}

/**
 * Matcher for localizing any disease name and details based on current language.
 * Bulletproof: handles UUIDs, English names, localized names, slugs, and partial queries.
 */
export function getLocalizedDisease(
  diseaseName?: string,
  cropType?: string,
  currentLang: string = 'en',
  diseaseId?: string
): {
  displayName: string;
  displayCrop: string;
  displayCategory: string;
  scientificName: string;
  symptoms: string[];
  causes: string;
  management: string[];
} {
  const lang = resolveEffectiveLanguage(currentLang);
  const normName = (diseaseName || '').trim().toLowerCase();
  const normCrop = (cropType || '').trim().toLowerCase();
  const normId = (diseaseId || '').trim().toLowerCase();

  // Find in structured catalog
  const match = MULTILINGUAL_DISEASE_CATALOG.find((entry) => {
    const id = entry.canonicalId.toLowerCase();

    // 1. Exact ID or slug match
    if (normId && (normId === id || normId.includes(id))) return true;
    if (normName === id || normName.includes(id)) return true;

    // 2. Specific crop-aware keyword matches
    if (normName.includes('brown spot') || (id === 'rice-brown-spot' && normName.includes('brown'))) {
      if (normCrop.includes('rice') || !normCrop) return true;
    }
    if ((normName.includes('blast') || normName.includes('குலை') || normName.includes('ಬೆಂಕಿ') || normName.includes('అగ్గి') || normName.includes('झुलसा')) && !normName.includes('blight')) {
      if (normCrop.includes('rice') || id.includes('blast')) return true;
    }
    if ((normName.includes('bacterial') && normName.includes('blight')) || id === 'rice-bacterial-blight') {
      if (normCrop.includes('rice') || !normCrop) return true;
    }
    if (normName.includes('early blight') || normName.includes('मुंदస్తు') || normName.includes('முன்கூட்டிய')) {
      if (normCrop.includes('potato') && id === 'potato-early-blight') return true;
      if (!normCrop.includes('potato') && id === 'tomato-early-blight') return true;
    }
    if (normName.includes('late blight') || normName.includes('మాడ') || normName.includes('பின்கூட்டிய')) {
      if (normCrop.includes('potato') && id === 'potato-late-blight') return true;
      if (!normCrop.includes('potato') && id === 'tomato-late-blight') return true;
    }
    if (normName.includes('mosaic') || id === 'tomato-mosaic-virus') {
      return true;
    }
    if ((normName.includes('common rust') || (normName.includes('rust') && normCrop.includes('maize'))) && id === 'maize-common-rust') {
      return true;
    }
    if ((normName.includes('gray leaf spot') || normName.includes('grey leaf spot')) && id === 'maize-gray-leaf-spot') {
      return true;
    }
    if ((normName.includes('yellow leaf curl') || normName.includes('tylcv')) && id === 'tomato-yellow-leaf-curl-virus') {
      return true;
    }
    if ((normName.includes('bacterial spot') || (normName.includes('spot') && normName.includes('bacterial'))) && id === 'tomato-bacterial-spot') {
      return true;
    }
    if (normName.includes('aphid') && id === 'multiple-aphids') {
      return true;
    }
    if (normName.includes('powdery mildew') && id === 'multiple-powdery-mildew') {
      return true;
    }
    if (normName.includes('downy mildew') && id === 'cucumber-downy-mildew') {
      return true;
    }
    if (normName.includes('whitefly') && id === 'tomato-whitefly') {
      return true;
    }
    if ((normName.includes('stripe rust') || (normName.includes('rust') && normCrop.includes('wheat'))) && id === 'wheat-rust') {
      return true;
    }

    // 3. Multilingual name exact/partial check across all translations
    return Object.values(entry.names).some((n) => {
      const low = n.toLowerCase();
      return low === normName || normName.includes(low) || low.includes(normName);
    });
  });

  // Localized crop lookup
  const cropEntry = CROP_LOCALIZATIONS[normCrop] || Object.entries(CROP_LOCALIZATIONS).find(([k]) => normCrop.includes(k))?.[1];
  const displayCrop = cropEntry?.[currentLang] || cropEntry?.[lang] || cropEntry?.en || cropType || 'Crop';

  if (match) {
    const displayName = match.names[lang] || match.names.en || diseaseName || match.canonicalId;
    const catKey = (match.categories.en || 'Fungal').toLowerCase();
    const catEntry = CATEGORY_LOCALIZATIONS[catKey];
    const displayCategory = catEntry?.[currentLang] || catEntry?.[lang] || catEntry?.en || match.categories[lang] || match.categories.en;

    const symptoms = match.symptoms?.[lang] || match.symptoms?.en || ['Symptomatic leaf spots observed on foliage.'];
    const causes = match.causes?.[lang] || match.causes?.en || 'Pathogen confirmed through agricultural inspection.';
    const management = match.management?.[lang] || match.management?.en || ['Apply recommended fungicide or biological treatment.'];

    return {
      displayName,
      displayCrop,
      displayCategory,
      scientificName: match.scientificName,
      symptoms,
      causes,
      management,
    };
  }

  // Safe Fallback
  const fallbackCat = CATEGORY_LOCALIZATIONS['fungal']?.[lang] || 'Fungal';
  return {
    displayName: diseaseName || 'Crop Disease',
    displayCrop,
    displayCategory: fallbackCat,
    scientificName: 'Phytopathology Specimen',
    symptoms: ['Foliar symptoms visible on leaf surface.'],
    causes: 'Crop pathology pathogen.',
    management: ['Apply recommended agricultural treatment.'],
  };
}

/**
 * Enhanced Search matching: checks English, Telugu, Tamil, Kannada, Malayalam, Marathi, Hindi,
 * scientific names, categories, and crop types.
 */
export function matchesDiseaseSearch(
  disease: { name: string; crop_type: string; category?: string; scientific_name?: string },
  query: string,
  currentLang: string = 'en'
): boolean {
  if (!query || !query.trim()) return true;
  const q = query.trim().toLowerCase();
  const lang = resolveEffectiveLanguage(currentLang);

  // Direct check
  if (disease.name.toLowerCase().includes(q)) return true;
  if (disease.crop_type.toLowerCase().includes(q)) return true;
  if (disease.category && disease.category.toLowerCase().includes(q)) return true;
  if (disease.scientific_name && disease.scientific_name.toLowerCase().includes(q)) return true;

  // Catalog check
  const loc = getLocalizedDisease(disease.name, disease.crop_type, lang);
  if (loc.displayName.toLowerCase().includes(q)) return true;
  if (loc.displayCrop.toLowerCase().includes(q)) return true;
  if (loc.displayCategory.toLowerCase().includes(q)) return true;
  if (loc.scientificName.toLowerCase().includes(q)) return true;

  // Check across all catalog languages for the disease
  const match = MULTILINGUAL_DISEASE_CATALOG.find(
    (e) => e.scientificName.toLowerCase().includes(q) ||
           Object.values(e.names).some((n) => n.toLowerCase().includes(q) || q.includes(n.toLowerCase())) ||
           Object.values(e.crops).some((c) => c.toLowerCase().includes(q))
  );

  if (match) return true;

  return false;
}
